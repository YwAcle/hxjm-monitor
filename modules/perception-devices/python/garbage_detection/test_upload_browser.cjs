const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = process.env.UPLOAD_TEST_URL;
    await page.goto(url);
    await page.locator('#upload-mode').click();
    assert.equal(await page.locator('#detect-button').isDisabled(), true);
    await page.locator('#image-file').setInputFiles('.runtime/upload-test.png');
    await page.waitForFunction(() => !document.getElementById('detect-button').disabled);
    await page.waitForFunction(() => document.getElementById('upload-image').naturalWidth === 800);
    assert.equal(await page.locator('#camera-image').isVisible(), false);
    await page.locator('#detailed-detection').check();
    await page.locator('#detection-threshold').focus();
    await page.keyboard.press('ArrowLeft');
    await page.screenshot({ path: '.runtime/upload-desktop.png', fullPage: true });
    await page.locator('#detect-button').click();
    const completed = page.waitForResponse(response => response.url().endsWith('/api/result'));
    await page.locator('#camera-mode').click();
    await completed;
    assert.equal(await page.locator('#result-detail').isVisible(), false);
    await page.locator('#upload-mode').click();
    await page.waitForSelector('.detection-box');
    const response = await page.request.get(`${url}/api/result`);
    const { result } = await response.json();
    assert.equal(result.source, 'upload');
    assert.equal(result.camera_id, null);
    assert.equal(result.file_name, 'upload-test.png');
    assert.equal(result.threshold, .2);
    assert.equal(result.passes, 6);
    assert.equal(await page.locator('#target-count').textContent(), '1个');
    assert.equal(await page.locator('.map-cell.occupied').textContent(), '左下');
    await page.waitForFunction(() => document.getElementById('result-image').naturalWidth === 800);
    await page.screenshot({ path: '.runtime/upload-result.png', fullPage: true });
    await page.locator('#live-tab').click();
    assert.equal(await page.locator('#upload-image').isVisible(), true);
    assert.equal(await page.locator('#boxes').isVisible(), false);
    await page.locator('#camera-mode').click();
    assert.equal(await page.locator('#result-tab').isDisabled(), true);
    assert.equal(await page.locator('#result-detail').isVisible(), false);
    await page.locator('#upload-mode').click();
    assert.equal(await page.locator('#result-detail').isVisible(), true);
    const downloadReady = page.waitForEvent('download');
    await page.locator('#export-button').click();
    await (await downloadReady).saveAs('.runtime/upload-export.json');
    const exported = JSON.parse(fs.readFileSync('.runtime/upload-export.json'));
    assert.equal(exported.source, 'upload');
    assert.equal(exported.camera_id, null);
    assert.equal('image' in exported, false);
    await page.locator('#image-file').setInputFiles({ name: 'second.png', mimeType: 'image/png', buffer: fs.readFileSync('.runtime/upload-test.png') });
    await page.waitForFunction(() => document.getElementById('file-name').textContent === 'second.png');
    assert.equal(await page.locator('#result-tab').isDisabled(), true);
    assert.equal(await page.locator('.detection-box').count(), 0);
    await page.locator('#image-file').setInputFiles({ name: 'bad.png', mimeType: 'image/png', buffer: Buffer.from('not an image') });
    await page.waitForFunction(() => document.getElementById('file-name').textContent.includes('未载入'));
    assert.equal(await page.locator('#detect-button').isDisabled(), true);
    const invalid = await page.request.post(`${url}/api/detect-image`, { headers: { 'Content-Type': 'image/png' }, data: Buffer.from('invalid image') });
    assert.equal(invalid.status(), 400);
    const crossOrigin = await page.request.post(`${url}/api/detect-image`, { headers: { Origin: 'http://foreign.invalid' }, data: fs.readFileSync('.runtime/upload-test.png') });
    assert.equal(crossOrigin.status(), 403);
    const invalidThreshold = await page.request.post(`${url}/api/detect-image`, { headers: { 'X-Detection-Threshold': 'NaN' }, data: fs.readFileSync('.runtime/upload-test.png') });
    assert.equal(invalidThreshold.status(), 400);
    // Camera choice is local to the viewer; results and exports stay with their source.
    await page.locator('#camera-mode').click();
    assert.equal(await page.locator('.camera-option').count(), 4);
    await page.locator('[data-camera="camera_1"]').click();
    await page.waitForFunction(() => document.getElementById('camera-status').textContent.includes('摄像头 1 已连接'));
    await page.waitForFunction(() => document.getElementById('camera-image').naturalWidth === 800);
    const cameraStarted = page.waitForResponse(r => r.url().endsWith('/api/detect') && r.status() === 202);
    await page.locator('#detect-button').click();
    await cameraStarted;
    await page.locator('[data-camera="camera_4"]').click();
    assert.equal(await page.locator('#result-tab').isDisabled(), true);
    await page.waitForFunction(() => document.getElementById('camera-status').textContent.includes('摄像头 4 已连接'));
    await page.waitForFunction(async () => (await (await fetch('/api/state')).json()).job.state === 'done');
    await page.waitForTimeout(1500);
    assert.equal(await page.locator('#result-detail').isVisible(), false);
    await page.locator('[data-camera="camera_1"]').click();
    await page.waitForSelector('.detection-box');
    const cameraResult = (await (await page.request.get(`${url}/api/result`)).json()).result;
    assert.equal(cameraResult.camera_id, 'camera_1');
    const cameraDownloadReady = page.waitForEvent('download');
    await page.locator('#export-button').click();
    const cameraDownload = await cameraDownloadReady;
    assert.match(cameraDownload.suggestedFilename(), /^camera_1_/);
    await cameraDownload.saveAs('.runtime/camera-export.json');
    assert.equal(JSON.parse(fs.readFileSync('.runtime/camera-export.json')).camera_id, 'camera_1');
    assert.equal(await page.locator('#category-summary').textContent(), '测试目标 × 1');
    assert.equal(await page.locator('#category-total').textContent(), '14');
    await page.locator('[data-camera="camera_2"]').click();
    await page.waitForFunction(() => document.getElementById('camera-status').textContent.includes('摄像头 2 未连接'));
    assert.equal(await page.locator('#detect-button').isDisabled(), true);
    assert.equal(await page.locator('#result-tab').isDisabled(), true);
    const badCamera = await page.request.post(`${url}/api/detect`, { headers: { 'X-Camera-Id': 'camera_9' } });
    assert.equal(badCamera.status(), 400);
    const badFrame = await page.request.get(`${url}/api/frame.jpg?camera_id=camera_9`);
    assert.equal(badFrame.status(), 400);
    const otherView = await browser.newPage();
    await otherView.goto(url);
    await otherView.locator('[data-camera="camera_4"]').click();
    await otherView.waitForFunction(() => document.getElementById('camera-status').textContent.includes('摄像头 4 已连接'));
    assert.match(await page.locator('#source-title').textContent(), /摄像头 2/);
    await otherView.close();
    await page.locator('[data-camera="camera_4"]').click();
    await page.waitForFunction(() => document.getElementById('camera-image').naturalWidth === 800);
    await page.screenshot({ path: '.runtime/camera-switch-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: '.runtime/upload-mobile.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: upload, four camera buttons, selection during detection, independent viewers, offline/invalid camera, source-specific results/export, categories and mobile layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
